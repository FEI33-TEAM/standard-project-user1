export default function FaqPage() {
  const [openIndex, setOpenIndex] = useState(null);

  function toggle(i) {
    setOpenIndex((prev) => (prev === i ? null : i));
  }

  return (
    <main className="page-content">
      <div className="stub-banner">
        <span>🚧</span>
        <span>Ця сторінка є заглушкою — спробуй додати нове питання в масив!</span>
      </div>

      <h1>❓ Часті запитання (FAQ)</h1>
      <p style={{ marginBottom: '1.5rem' }}>
        Відповіді на найпоширеніші запитання про розмитнення авто.
      </p>

      {faqs.map((faq, i) => (
        <div className="faq-item" key={i}>
          <div
            className={`faq-question${openIndex === i ? ' open' : ''}`}
            onClick={() => toggle(i)}
            role="button"
            tabIndex={0}
            onKeyDown={(e) => e.key === 'Enter' && toggle(i)}
          >
            <span>{faq.q}</span>
            <span>{openIndex === i ? '▲' : '▼'}</span>
          </div>
          {openIndex === i && (
            <div className="faq-answer">{faq.a}</div>
          )}
        </div>
      ))}
    </main>
  );
}
